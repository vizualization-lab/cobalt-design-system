#!/usr/bin/env node

/**
 * Assembles dist/pre-upgrade.css from the per-component fragments at
 * src/components/<name>/co-<name>.pre-upgrade.css.
 *
 * The assembled stylesheet is the published artifact (`@cobalt/components/pre-upgrade.css`).
 * Consumers import the single file; never the per-component fragments.
 *
 * Usage:
 *   node scripts/build-pre-upgrade.js          # one-shot build
 *   node scripts/build-pre-upgrade.js --watch  # re-assemble on source changes
 *   node scripts/build-pre-upgrade.js --check  # exit 1 if dist is out of date
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
  watch as fsWatch,
} from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const componentsDir = join(__dirname, '..', 'src', 'components');
const distDir = join(__dirname, '..', 'dist');
const outputPath = join(distDir, 'pre-upgrade.css');

const args = process.argv.slice(2);
const isCheck = args.includes('--check');
const isWatch = args.includes('--watch');

/**
 * Walk src/components/<name>/ and return every per-component pre-upgrade fragment.
 */
function findFragments() {
  const fragments = [];
  const entries = readdirSync(componentsDir, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const fragmentPath = join(componentsDir, entry.name, `co-${entry.name}.pre-upgrade.css`);
    if (!existsSync(fragmentPath)) continue;
    fragments.push({ tag: `co-${entry.name}`, path: fragmentPath });
  }
  fragments.sort((a, b) => a.tag.localeCompare(b.tag));
  return fragments;
}

/**
 * Strip leading block comments and surrounding whitespace from a fragment so the
 * rule body can be re-nested inside @layer co.reset { ... } without dragging in
 * the per-fragment file header.
 */
function stripLeadingComments(content) {
  return content.replace(/^\s*(?:\/\*[\s\S]*?\*\/\s*)*/, '').trimEnd();
}

/**
 * Indent each line of `text` by `prefix`.
 */
function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line.length === 0 ? line : prefix + line))
    .join('\n');
}

function buildOutput(fragments) {
  const tags = fragments.map((f) => f.tag);
  const tagList = wrapTagList(tags);
  const header = `/*
 * Cobalt pre-upgrade defaults — ASSEMBLED FILE, DO NOT EDIT DIRECTLY.
 *
 * Generated by scripts/build-pre-upgrade.js from per-component fragments at
 * src/components/<name>/co-<name>.pre-upgrade.css. Edit the per-component
 * source files instead and rebuild.
 *
 * Each rule suppresses flash-of-unstyled-content (FOUC) by reserving the
 * layout shape that the upgraded :host will occupy and hiding slotted
 * content via visibility: hidden. The :not(:defined) qualifier disengages
 * the rule the moment customElements.define() runs.
 *
 * This stylesheet depends on @cobalt/tokens/css being loaded first so the
 * custom-property references resolve at first paint.
 *
 * Components included (${tags.length}):
${tagList}
 */
`;

  const body = fragments
    .map(({ tag, path }) => {
      const rule = stripLeadingComments(readFileSync(path, 'utf-8'));
      return `  /* ${tag} */\n${indent(rule, '  ')}`;
    })
    .join('\n\n');

  return `${header}\n@layer co.reset {\n${body}\n}\n`;
}

function wrapTagList(tags) {
  const lines = [];
  let current = ' *  ';
  for (const tag of tags) {
    const next = current === ' *  ' ? `${current}${tag}` : `${current}, ${tag}`;
    if (next.length > 78) {
      lines.push(current);
      current = ` *  ${tag}`;
    } else {
      current = next;
    }
  }
  if (current.trim() !== '*') lines.push(current);
  return lines.join('\n');
}

function buildOnce() {
  const fragments = findFragments();
  if (fragments.length === 0) {
    console.error('No pre-upgrade fragments found under src/components/*/co-*.pre-upgrade.css');
    process.exit(1);
  }

  const output = buildOutput(fragments);
  const existing = existsSync(outputPath) ? readFileSync(outputPath, 'utf-8') : '';

  if (existing === output) {
    if (isCheck) {
      console.log(`pre-upgrade.css is up to date (${fragments.length} components).`);
    }
    return true;
  }

  if (isCheck) {
    console.error(
      `Out of date: ${outputPath}\n` +
        'Run `npm run pre-upgrade:build` to regenerate from the per-component fragments.',
    );
    return false;
  }

  mkdirSync(distDir, { recursive: true });
  writeFileSync(outputPath, output);
  console.log(`Built ${outputPath} from ${fragments.length} component fragments.`);
  return true;
}

const ok = buildOnce();
if (isCheck && !ok) process.exit(1);

if (isWatch) {
  console.log('\nWatching src/components/*/co-*.pre-upgrade.css for changes...');
  fsWatch(componentsDir, { recursive: true }, (_event, filename) => {
    if (filename && filename.endsWith('.pre-upgrade.css')) {
      try {
        buildOnce();
      } catch (err) {
        console.error(`Error rebuilding pre-upgrade.css:`, err.message);
      }
    }
  });
}
